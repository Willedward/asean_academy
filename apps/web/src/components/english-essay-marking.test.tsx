import { cleanup, fireEvent, render, screen } from "@testing-library/react";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";

import type { EnglishEssayMarkingWorkspaceResponse } from "@/lib/api/english";

import { EnglishEssayMarking } from "./english-essay-marking";

const getMarking = vi.fn();
const createMarking = vi.fn();

vi.mock("@/lib/api/english", () => ({
  getEnglishEssayMarkingWorkspace: (...args: unknown[]) => getMarking(...args),
  createEnglishEssayMarkingJob: (...args: unknown[]) => createMarking(...args),
}));

const submissionId = "dfdb118f-b09d-4baf-a7e0-64f582729351";
const empty: EnglishEssayMarkingWorkspaceResponse = {
  submission_id: submissionId,
  job: null,
  feedback: null,
  learner_disclaimer: "Development fixture only.",
};
const complete: EnglishEssayMarkingWorkspaceResponse = {
  submission_id: submissionId,
  learner_disclaimer: "Development fixture only.",
  job: {
    job_id: "0eb27047-91c6-4ab8-9668-844a20f790fe",
    submission_id: submissionId,
    rubric_key: "english-essay-rubric-instructional-v1",
    rubric_revision: 1,
    mode: "deterministic_fixture",
    status: "succeeded",
    attempt_count: 1,
    max_attempts: 3,
    run_after: "2026-10-31T01:00:00Z",
    last_error_code: null,
    last_error_message: null,
    created_at: "2026-10-31T01:00:00Z",
    updated_at: "2026-10-31T01:00:01Z",
    completed_at: "2026-10-31T01:00:01Z",
    external_provider_used: false,
  },
  feedback: {
    feedback_id: "e2ac5fd2-eefd-49a8-8867-b4f300196246",
    job_id: "0eb27047-91c6-4ab8-9668-844a20f790fe",
    submission_id: submissionId,
    rubric_key: "english-essay-rubric-instructional-v1",
    rubric_revision: 1,
    fixture_version: "english-essay-fixture-v1",
    criterion_feedback: [
      {
        criterion_key: "task_fulfilment",
        criterion_title: "Task fulfilment and focus",
        observed_evidence: "The response opens with a concrete example.",
        what_works: "The response addresses the prompt.",
        next_step: "Connect every example to the central insight.",
      },
    ],
    overall_summary: "Preserve the example and clarify the insight.",
    strengths: ["A concrete experience anchors the response."],
    priorities: ["Make the central insight explicit."],
    learner_disclaimer:
      "This feedback was generated by a deterministic development fixture, not a live AI marker.",
    created_at: "2026-10-31T01:00:01Z",
    immutable: true,
    fixture_generated: true,
    ai_feedback_available: false,
    official_score_available: false,
  },
};

beforeEach(() => {
  getMarking.mockReset();
  createMarking.mockReset();
});

afterEach(cleanup);

describe("EnglishEssayMarking", () => {
  it("queues fixture feedback only after an explicit learner request", async () => {
    getMarking.mockResolvedValueOnce(empty).mockResolvedValueOnce(complete);
    createMarking.mockResolvedValue({
      ...empty,
      job: { ...complete.job!, status: "queued", attempt_count: 0 },
    });

    render(<EnglishEssayMarking submissionId={submissionId} />);
    const button = await screen.findByRole("button", {
      name: "Generate fixture feedback",
    });
    expect(screen.getByText(/makes no paid API call/)).toBeInTheDocument();
    fireEvent.click(button);

    expect(
      await screen.findByText("Structured revision feedback"),
    ).toBeInTheDocument();
    expect(
      screen.getByText("This is not live AI marking."),
    ).toBeInTheDocument();
    expect(screen.getByText("Task fulfilment and focus")).toBeInTheDocument();
    expect(createMarking).toHaveBeenCalledWith(submissionId);
  });

  it("restores immutable completed fixture feedback", async () => {
    getMarking.mockResolvedValue(complete);
    render(<EnglishEssayMarking submissionId={submissionId} />);

    expect(
      await screen.findByText("Preserve the example and clarify the insight."),
    ).toBeInTheDocument();
    expect(screen.getByText("Fixture complete")).toBeInTheDocument();
    expect(
      screen.queryByRole("button", { name: "Generate fixture feedback" }),
    ).not.toBeInTheDocument();
  });
});
